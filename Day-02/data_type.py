# Python Data Types
# Integer
year = 2026
print("Year: ", year)
print("Type: ",  type(year))

#Float
Temp = 46.7
print("\nToday temp is: ", Temp)
print(type(Temp))

# String
country = "India"
print ("\nCountry name is: ", country)
print (type(country))

# Boolean
is_Temp_high = True
print("\nis today's temp is high ? ", is_Temp_high)
print(type(is_Temp_high))

# List

countries = ["India", "Dubai","Japan"]
print("\nCountries :", countries)
print(type(countries))

# Tuple
fruits = ("orange", "Banana", "Mango")
print("\nfruits : ", fruits)
print(type(fruits))

# Dictionary
student = {
    "Name" : "Raju",
    "id" : 2
}
print("\nStudent:", student)
print("Type:", type(student))