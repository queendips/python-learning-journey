# Check Positive, Negative, or Zero
num = int (input("Enter a number : "))
if num > 0:
    print("It is positive number")
elif num < 0:
    print("It is negative number")
else:
    print("Zero")


# Example 2: Grade Calculator

marks = 75

if marks >= 90:
    print("Grade A")
elif marks >= 75:
    print("Grade B")
elif marks >= 60:
    print("Grade C")
else:
    print("Grade D")