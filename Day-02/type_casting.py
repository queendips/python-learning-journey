# Type Casting in Python

# Integer to Float
num = 10
print("original value: ", num)
print("type of num: ", type(num))

num_float = float(num)
print("After Type Casting:", num_float)
print("New Type:", type(num_float))

# Float to Integer
temp = 46.7
temp_int = int(temp)
print("\noriginalvalue :", temp)
print("Original type: ", type(temp))
print("After type casting: ", temp_int)
print("New type: ", type(temp_int))

# Integer to String
year = 2026
year_str = str(year)

print("\nOriginal Value:", year)
print("Original Type: ", type(year))
print("After Type Casting:", year_str)
print("New type: ", type(year_str))

# String to Integer
num_str = "100"
num_int = int(num_str)

print("\nOriginal Value:", num_str)
print("original type: ", type(num_str))
print("After Type Casting:", num_int)
print("New Type: ", type(num_int))