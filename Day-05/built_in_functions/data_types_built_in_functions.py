# int()
age = int("25")
print(age)

# float()
salary = float("25000.50")
print(salary)
print(int(salary))

# list()
fruits = list(("Apple", "Mango", "Banana"))
print(fruits)
print(type(fruits))

# tuple()
colors = tuple(["Red", "Blue", "Green"])
print(colors)
print(type(colors))

# set()
numbers = set([1, 2, 2, 3, 3, 4])
print(numbers)
print(type(numbers))

# dict()
student = dict(name="Dipali", age=25)
print(student)
print(type(student))

# str()
employee_id = 101

print(employee_id)
print(type(employee_id))

employee_id = str(employee_id)

print(employee_id)
print(type(employee_id))