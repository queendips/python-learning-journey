for num in range(5):
    print("Value of num :",num)

for j in range(1, 6):
    print("value of j:", j)
# Step Value
for i in range(2,11,2):
    print("value of i : ", i)

for ticket in range(101, 106):
    print("Ticket Number:", ticket)

# Reverse Counting

for count in range(10, 0, -1):
    print("Value of count: ", count)